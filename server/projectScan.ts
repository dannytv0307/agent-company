// Reads what a project repo already brings — CLAUDE.md, its own agents, skills, commands — without changing it.
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs'
import path from 'node:path'
import YAML from 'yaml'
import type { ProjectScan } from '../shared/types.ts'

export const GENERATED_MARK = 'Generated by Agent Company'
const ROADMAPS = ['docs/journey.md', 'docs/roadmap.md', 'ROADMAP.md', 'docs/plan.md']

function frontmatter(file: string): Record<string, unknown> {
  const m = readFileSync(file, 'utf8').match(/^---\r?\n([\s\S]*?)\r?\n---/)
  if (!m) return {}
  try {
    return (YAML.parse(m[1]) as Record<string, unknown>) ?? {}
  } catch {
    // Claude Code tolerates unquoted values like "description: Art Director — style: …" that strict YAML rejects.
    const out: Record<string, unknown> = {}
    for (const line of m[1].split(/\r?\n/)) {
      const kv = line.match(/^([A-Za-z_][\w-]*):\s*(.*)$/)
      if (kv) out[kv[1]] = kv[2].replace(/^["']|["']$/g, '')
    }
    return out
  }
}

const generated = (file: string) => readFileSync(file, 'utf8').includes(GENERATED_MARK)
const list = (v: unknown) => (Array.isArray(v) ? v.map(String) : typeof v === 'string' ? v.split(',').map((s) => s.trim()).filter(Boolean) : undefined)
const humanize = (id: string) =>
  id
    .split(/[-_\s]+/)
    .filter(Boolean)
    .map((w) => (w.length <= 2 ? w.toUpperCase() : w[0].toUpperCase() + w.slice(1)))
    .join(' ')

/** "Art Director — defines the visual style…" → "Art Director" */
function roleOf(id: string, description: string): string {
  const head = description.split(/\s[—–-]\s|[.:]\s/)[0].trim()
  return head && head.length <= 48 ? head : humanize(id)
}

const cache = new Map<string, { at: number; scan: ProjectScan }>()

export function scanProject(dir: string): ProjectScan | undefined {
  if (!existsSync(dir)) return undefined
  const hit = cache.get(dir)
  if (hit && Date.now() - hit.at < 5000) return hit.scan
  const claudeDir = path.join(dir, '.claude')
  const agentsDir = path.join(claudeDir, 'agents')
  const skillsDir = path.join(claudeDir, 'skills')
  const commandsDir = path.join(claudeDir, 'commands')
  const md = (p: string) => existsSync(p) && statSync(p).isFile()

  const agents: ProjectScan['agents'] = []
  if (existsSync(agentsDir)) {
    for (const f of readdirSync(agentsDir).filter((n) => n.endsWith('.md'))) {
      const file = path.join(agentsDir, f)
      if (generated(file)) continue
      const fm = frontmatter(file)
      const id = String(fm.name ?? f.replace(/\.md$/, ''))
      const description = String(fm.description ?? '')
      agents.push({ id, role: roleOf(id, description), description, tools: list(fm.tools), model: fm.model ? String(fm.model) : undefined })
    }
  }

  const skills: ProjectScan['skills'] = []
  if (existsSync(skillsDir)) {
    for (const d of readdirSync(skillsDir)) {
      const file = path.join(skillsDir, d, 'SKILL.md')
      if (!md(file)) continue
      const fm = frontmatter(file)
      skills.push({ name: String(fm.name ?? d), description: String(fm.description ?? '') })
    }
  }

  const commands = existsSync(commandsDir) ? readdirSync(commandsDir).filter((n) => n.endsWith('.md')).map((n) => n.replace(/\.md$/, '')) : []
  const agentsMdFile = path.join(dir, 'AGENTS.md')

  const scan: ProjectScan = {
    claudeMd: md(path.join(dir, 'CLAUDE.md')) && !generated(path.join(dir, 'CLAUDE.md')),
    agentsMd: md(agentsMdFile) && !generated(agentsMdFile),
    settings: md(path.join(claudeDir, 'settings.json')),
    mcp: md(path.join(dir, '.mcp.json')),
    agents,
    skills,
    commands,
    roadmap: ROADMAPS.find((r) => md(path.join(dir, r))),
  }
  cache.set(dir, { at: Date.now(), scan })
  return scan
}

export { humanize }

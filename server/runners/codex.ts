// Runs one Codex agent headless (`codex exec --json`) and maps its JSONL stream to events.
import { existsSync, readFileSync } from 'node:fs'
import path from 'node:path'
import type { ChildProcess } from 'node:child_process'
import type { AgentRef, OrgDef, Sandbox } from '../../shared/types.ts'
import { bus } from '../events.ts'
import { MCP_SERVER, PORT, persona } from '../compile.ts'
import { onLines, resolveBin, spawnCli } from '../proc.ts'
import { short } from './summarize.ts'

export const codexChildren = new Set<ChildProcess>()

/** Codex on Windows wraps commands in `powershell.exe -Command '…'` — show only the inner command. */
function cleanCommand(cmd: unknown): string {
  const s = Array.isArray(cmd) ? cmd.join(' ') : String(cmd ?? '')
  const m = s.match(/(?:powershell|pwsh|bash|sh)(?:\.exe)?"?\s+(?:-\w+\s+)*?-(?:Command|c|lc)\s+(.+)$/i)
  return (m ? m[1] : s).replace(/^['"]|['"]$/g, '')
}

/**
 * Codex reads AGENTS.md but not CLAUDE.md or .claude/skills. When the repo keeps its rules there,
 * pass them along so both divisions follow the same conventions.
 */
export function repoContext(dir: string): string {
  const parts: string[] = []
  const claudeMd = path.join(dir, 'CLAUDE.md')
  if (existsSync(claudeMd)) {
    const text = readFileSync(claudeMd, 'utf8')
    if (!text.includes('Generated by Agent Company')) parts.push(`Project rules (from the repo's CLAUDE.md — follow them):\n${text.slice(0, 6000)}`)
  }
  const skills = path.join(dir, '.claude', 'skills')
  if (existsSync(skills)) parts.push('The repo documents its workflows as skills in .claude/skills/<name>/SKILL.md — read the relevant one before that kind of work.')
  return parts.length ? `\n\n${parts.join('\n\n')}` : ''
}

function codexPrompt(org: OrgDef, agent: AgentRef, from: string, task: string, intro: string): string {
  const lead = agent.isCeo
    ? `\n\nYou can delegate to your team with the \`delegate\` MCP tool (from = "${agent.id}"). Use \`list_colleagues\` to see who is available.`
    : ''
  return `${intro}${lead}\n\n---\nTask from ${from}:\n${task}\n\nEnd with a concise report (max 10 lines).`
}

interface CodexOpts {
  /** Project folder the agent works in. */
  dir: string
  /** Assignment and plan task this run belongs to. */
  aid?: string
  taskId?: string
  /** Replaces the persona at the top of a fresh thread (the CEO's brief). */
  intro?: string
  sandbox?: Sandbox
  onChild?: (child: ChildProcess) => void
  /** Send `task` as-is (already a complete prompt) instead of wrapping it in the persona. */
  raw?: boolean
  /** Continue an earlier Codex thread. */
  resume?: string
  onThread?: (id: string) => void
}

export function runCodexAgent(org: OrgDef, agent: AgentRef, from: string, task: string, runId: string | undefined, opts: CodexOpts): Promise<string> {
  const bin = resolveBin('codex')
  if (!bin) return Promise.reject(new Error('Codex CLI not found. Install `@openai/codex` or the ChatGPT/Codex IDE extension and sign in.'))

  const sandbox = opts.sandbox ?? agent.sandbox ?? 'read-only'
  const args = opts.resume
    ? ['exec', 'resume', '--json', '--skip-git-repo-check', '-c', `sandbox_mode="${sandbox}"`]
    : ['exec', '--json', '--skip-git-repo-check', '-C', opts.dir, '-s', sandbox]
  // A Claude model name (opus, sonnet, haiku, claude-…) means nothing to Codex — use its default.
  if (agent.model && !/^(opus|sonnet|haiku|claude)/i.test(agent.model)) args.push('-m', agent.model)
  // Every Codex agent gets the company MCP tools (inbox, messaging the owner; the lead also delegates).
  const mcp = 'mcp_servers.agent-company'
  args.push(
    '-c', `${mcp}.command="node"`,
    '-c', `${mcp}.args=[${JSON.stringify(MCP_SERVER)}]`,
    '-c', `${mcp}.env={AGENT_COMPANY_URL="http://127.0.0.1:${PORT}", AGENT_COMPANY_RUN="${runId ?? ''}"}`,
    '-c', `${mcp}.tool_timeout_sec=1800`,
    // codex exec cannot ask anyone to approve a tool call, and these tools are the app's own.
    '-c', `${mcp}.default_tools_approval_mode="approve"`,
  )
  if (opts.resume) args.push(opts.resume, '-')

  // Personas (and the repo's Claude-side rules, which Codex does not read) go on a fresh thread only.
  const intro = opts.intro ?? `${persona(org, agent)}${repoContext(opts.dir)}`
  const prompt = opts.raw ? (opts.resume ? task : `${intro}\n\n---\n${task}`) : codexPrompt(org, agent, from, task, intro)

  return new Promise((resolve, reject) => {
    const child = spawnCli(bin, args, { cwd: opts.dir })
    codexChildren.add(child)
    opts.onChild?.(child)
    let last = ''
    let failure = ''

    onLines(child.stdout, (line) => {
      let ev: any
      try {
        ev = JSON.parse(line)
      } catch {
        return
      }
      const item = ev.item ?? {}
      const say = (text: string, file?: string) =>
        bus.emit({ runId, kind: 'activity', agent: agent.id, text, meta: { aid: opts.aid ?? runId, taskId: opts.taskId, ...(file ? { file } : {}) } })

      if (ev.type === 'thread.started') {
        if (ev.thread_id) opts.onThread?.(ev.thread_id)
        bus.emit({ runId, kind: 'system', agent: agent.id, text: 'Codex session started', meta: { threadId: ev.thread_id } })
      } else if (ev.type === 'item.started' && item.type === 'command_execution') {
        say(`$ ${short(cleanCommand(item.command), 56)}`)
      } else if (ev.type === 'item.started' && item.type === 'mcp_tool_call') {
        if (!['delegate', 'check_messages'].includes(item.tool)) say(`Using ${item.server}.${item.tool}`)
      } else if (ev.type === 'item.completed') {
        if (item.type === 'agent_message' && item.text) {
          last = item.text
          say(short(item.text, 90))
        } else if (item.type === 'reasoning' && item.text) {
          say(`💭 ${short(item.text, 80)}`)
        } else if (item.type === 'file_change') {
          const changes = (item.changes ?? []).map((c: any) => path.relative(opts.dir, path.resolve(opts.dir, String(c.path))).split(path.sep).join('/'))
          say(`Editing ${short(changes.map((c: string) => c.split('/').pop()).join(', '), 50)}`, changes[0])
        } else if (item.type === 'web_search') {
          say(`Researching ${short(item.query, 48)}`)
        } else if (item.type === 'error') {
          failure = item.message ?? 'error'
        }
      } else if (ev.type === 'turn.failed' || ev.type === 'error') {
        failure = ev.error?.message ?? ev.message ?? 'Codex turn failed'
      }
    })

    let stderr = ''
    child.stderr?.on('data', (d) => (stderr += d))
    child.on('error', (e) => {
      codexChildren.delete(child)
      reject(e)
    })
    child.on('close', (code) => {
      codexChildren.delete(child)
      if (last && !failure) resolve(last)
      else reject(new Error(failure || short(stderr, 300) || `codex exited with code ${code}`))
    })
    child.stdin?.end(prompt)
  })
}

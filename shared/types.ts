// Types shared by the server and the web UI.

export type Lang = 'en' | 'ja'
export type L10n = Record<Lang, string>
export type Runtime = 'claude' | 'codex' | 'antigravity'
export type Sandbox = 'read-only' | 'workspace-write'

export interface AgentDef {
  id: string
  name: L10n
  role: L10n
  avatar: string
  color: string
  description: string
  model?: string
  prompt?: string
  tools?: string[]
  sandbox?: Sandbox
  /** Core roles (CEO, HR) cannot be dismissed by agents. */
  core?: boolean
  /** How many tasks this person may work on at the same time (default 2). */
  maxConcurrent?: number
  /** The company CEO only: which engine runs them (default: their division's, i.e. Claude Code). */
  runtime?: Runtime
}

export interface DepartmentDef {
  id: string
  name: L10n
  icon: string
  members: AgentDef[]
}

export interface DivisionDef {
  id: string
  runtime: Runtime
  label: L10n
  color: string
  mode?: 'auto' | 'manual'
  permissions?: { mode?: string; allow?: string[] }
  ceo?: AgentDef
  departments: DepartmentDef[]
}

export interface OwnerDef {
  id: string
  name: L10n
  title: L10n
  avatar: string
  /** Who the owner is and how they like to work — shared with the CEO. */
  bio?: string
  preferences?: {
    /** manual: org changes wait for the owner's approval. auto: applied immediately. */
    approval?: 'manual' | 'auto'
    /** Language agents use when reporting to the owner. */
    reportLanguage?: string
    /**
     * When the organizer stops for the owner's go-ahead (ask_owner):
     * key — spec, plan and each milestone (default); plan — the plan only; blocked — only when stuck.
     */
    checkIns?: CheckIns
    /** Stop any run, chat reply or task still going after this many minutes (unset = never). */
    autoStopMinutes?: number
  }
}

export type CheckIns = 'key' | 'plan' | 'blocked'

/** Something running that the owner can stop: an organizer run, a 1:1 chat reply, or a delegated task. */
export interface WorkItem {
  id: string
  kind: 'run' | 'chat' | 'task'
  projectId: string
  agentId: string
  /** Who handed a task over. */
  from?: string
  engine: 'claude' | 'codex'
  title: string
  startedAt: number
  /** queued: waiting for a free slot (the agent's parallel limit). */
  status: 'queued' | 'running'
  runId?: string
  /** The assignment id its events carry. */
  aid?: string
}

export interface RepoCommand {
  name: string
  description?: string
  argumentHint?: string
}

export type CheckpointKind = 'spec' | 'plan' | 'milestone' | 'decision'

/**
 * A break point where the organizer stops for the owner: a spec or plan to confirm, a finished
 * milestone, or a choice. The organizer waits for the answer; a late answer resumes its session.
 */
export interface Checkpoint {
  id: string
  ts: number
  projectId: string
  runId?: string
  agentId: string
  kind: CheckpointKind
  title: string
  /** Markdown: the spec, the plan, what was done, or the question. */
  body: string
  /** A document in the repo with the full text, e.g. docs/spec/booking.md. */
  file?: string
  /** For decisions: the choices offered. */
  options?: string[]
  status: 'open' | 'answered'
  /** approve | changes | reply | one of the options */
  answer?: { decision: string; comment?: string; ts: number }
}

/** A folder the company works in. Its team is the repo's own `.claude/agents`; the CEO leads every project. */
export interface ProjectDef {
  id: string
  name: string
  /** Absolute, or relative to the app folder. */
  path: string
  /** Extra Claude Code tool rules allowed in this project, e.g. "WebSearch", "WebFetch", "Bash(python *)". */
  allow?: string[]
  /** Codex agents may use the network inside their sandbox (scripts that download data, package installs). */
  codexNetwork?: boolean
}

/** Permissions the organizer asks for on a project; the owner approves them like a team change. */
export interface PermissionRequest {
  /** Claude Code tool rules, e.g. ["WebSearch", "WebFetch", "Bash(python *)"]. */
  tools?: string[]
  codexNetwork?: boolean
}

/** What the repo already brings: rules, its own agents, skills and commands. Read-only. */
export interface ProjectScan {
  claudeMd: boolean
  /** An AGENTS.md written by the owner (not generated by the app). */
  agentsMd: boolean
  settings: boolean
  mcp: boolean
  /**
   * The repo's own agents: .claude/agents (run by Claude Code) and .codex/agents (run by Codex, which has
   * no agent files of its own — the app runs them with `codex exec`). `created`: written by the app after a hire.
   */
  agents: {
    id: string
    role: string
    description: string
    tools?: string[]
    model?: string
    created?: boolean
    runtime?: 'claude' | 'codex'
    sandbox?: Sandbox
    /** Codex agents: the file's body, their working instructions. */
    prompt?: string
  }[]
  skills: { name: string; description: string }[]
  /** Slash commands (.claude/commands), run as `/name args`. */
  commands: RepoCommand[]
  /** A roadmap document the repo already keeps (e.g. docs/journey.md). */
  roadmap?: string
}

export interface ProjectRef extends ProjectDef {
  /** Resolved absolute folder. */
  dir: string
  exists: boolean
  scan?: ProjectScan
}

export type TaskStatus = 'todo' | 'doing' | 'review' | 'done' | 'blocked'

export interface PlanTask {
  id: string // "T1"
  title: string
  milestone?: string // "M1"
  assignee?: string
  status: TaskStatus
  note?: string
  updatedAt: number
}

/** The CEO's plan for one project. Progress = done tasks / all tasks. */
export interface Plan {
  projectId: string
  goal?: string
  milestones: { id: string; title: string }[]
  tasks: PlanTask[]
  updatedAt: number
}

export interface CompanyDef {
  name: L10n
  projects?: ProjectDef[]
  /** Where new tasks and chats go by default. */
  activeProject?: string
  /** Legacy single-folder setting; becomes the "Main" project. */
  workspace?: string
  /** What the business does. Empty until the CEO designs the company. */
  mission?: string
  rules?: string
}

export interface OrgDef {
  company: CompanyDef
  owner: OwnerDef
  divisions: DivisionDef[]
}

/** An agent the CEO wants on a project's team. Approved, it becomes `.claude/agents/<id>.md` in that repo. */
export interface HireSpec {
  id: string
  description: string
  prompt?: string
  tools?: string[]
  model?: string
  /** claude (default) → .claude/agents; codex → .codex/agents */
  runtime?: 'claude' | 'codex'
  /** Codex only: read-only for pure reviewers, workspace-write (default) when it writes files. */
  sandbox?: Sandbox
}

/** A whole team for one project, proposed in one go. */
export interface TeamDesign {
  agents: HireSpec[]
}

/** design = a team for the project; hire / dismiss = one agent in or out; permission = tools for the project. */
export type ProposalKind = 'design' | 'hire' | 'dismiss' | 'permission'

export interface Proposal {
  id: string
  ts: number
  kind: ProposalKind
  from: string
  reason: string
  status: 'pending' | 'approved' | 'rejected'
  design?: TeamDesign
  hire?: HireSpec
  dismiss?: { id: string }
  permission?: PermissionRequest
  /** The project whose team changes. */
  projectId?: string
}

export interface ChatMessage {
  id: string
  ts: number
  agentId: string
  role: 'owner' | 'agent' | 'note'
  text: string
  projectId?: string
  /** The agent asked the owner something (message_owner) and waits for an answer. */
  ask?: boolean
  /** The message announces a checkpoint the owner answers in place. */
  checkpointId?: string
  /** The message announces a team change the owner approves in place. */
  proposalId?: string
}

/** One project as seen from the portfolio. */
export interface ProjectSummary {
  id: string
  name: string
  dir: string
  exists: boolean
  /** How many agents the repo's team has. */
  team: number
  running: boolean
  progress: { done: number; total: number; pct: number }
  counts: Record<TaskStatus, number>
  milestone?: string
  next?: { id: string; title: string; assignee?: string }
  working: { agentId: string; title: string }[]
  lastActivity?: number
  costUsd: number
  needs: { approvals: number; decisions: number; questions: number; blocked: number; manual: number }
}

export interface FileChange {
  path: string
  status: string // git porcelain code, e.g. "M", "A", "??"
  added?: number
  removed?: number
  /** Who touched it (from agent events), most recent first. */
  by: { agentId: string; taskId?: string; ts: number }[]
}

export interface ProjectChanges {
  git: boolean
  branch?: string
  files: FileChange[]
  commits: { hash: string; subject: string; author: string; when: string }[]
}

/** An agent flattened with its position in the org. */
export interface AgentRef extends AgentDef {
  divisionId: string
  departmentId: string | null
  runtime: Runtime
  isCeo: boolean
  manual: boolean
  managerId: string
  /** Defined in a repo's `.claude/agents` (read-only in the app), for this project. */
  external?: string
}

export type EventKind =
  | 'task' // owner → CEO
  | 'dispatch' // manager → member (or cross-division)
  | 'report' // member → manager
  | 'activity' // what an agent is doing right now
  | 'manual' // task queued for a manual (non-automated) agent
  | 'error'
  | 'chat' // a message in an owner ↔ agent chat
  | 'system'

export interface AgentEvent {
  id: string
  ts: number
  runId?: string
  projectId?: string
  kind: EventKind
  from?: string
  to?: string
  agent?: string
  text: string
  meta?: Record<string, unknown>
}

export interface RuntimeStatus {
  runtime: Runtime
  installed: boolean
  version?: string
  path?: string
  auth: 'ok' | 'missing' | 'unknown'
  mode: 'auto' | 'manual'
  note?: string
}

export interface CompiledFile {
  path: string // relative to workspace
  runtime: Runtime | 'shared'
  agentId?: string
  content: string
}

export interface ManualTask {
  id: string
  ts: number
  from: string
  to: string
  task: string
  prompt: string
  done: boolean
}

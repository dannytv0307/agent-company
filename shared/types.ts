// Types shared by the server and the web UI.

export type Lang = 'en' | 'ja'
export type L10n = Record<Lang, string>
export type Runtime = 'claude' | 'codex' | 'antigravity'
export type Sandbox = 'read-only' | 'workspace-write'

export interface AgentDef {
  id: string
  name: L10n
  role: L10n
  avatar: string
  color: string
  description: string
  model?: string
  prompt?: string
  tools?: string[]
  sandbox?: Sandbox
  /** Core roles (CEO, HR) cannot be dismissed by agents. */
  core?: boolean
  /** How many tasks this person may work on at the same time (default 2). */
  maxConcurrent?: number
  /** The company CEO only: which engine runs them (default: their division's, i.e. Claude Code). */
  runtime?: Runtime
}

export interface DepartmentDef {
  id: string
  name: L10n
  icon: string
  members: AgentDef[]
}

export interface DivisionDef {
  id: string
  runtime: Runtime
  label: L10n
  color: string
  mode?: 'auto' | 'manual'
  permissions?: { mode?: string; allow?: string[] }
  ceo?: AgentDef
  departments: DepartmentDef[]
}

export interface OwnerDef {
  id: string
  name: L10n
  title: L10n
  avatar: string
  /** Who the owner is and how they like to work — shared with the CEO. */
  bio?: string
  preferences?: {
    /** manual: org changes wait for the owner's approval. auto: applied immediately. */
    approval?: 'manual' | 'auto'
    /** Language agents use when reporting to the owner. */
    reportLanguage?: string
  }
}

/**
 * Who works on a project:
 * company — the company's own team; project — the repo's own `.claude/agents`;
 * mixed — both (repo specialists + company roles such as HR and the Codex partner).
 */
export type TeamMode = 'company' | 'project' | 'mixed'

/** A folder the company works in. Agents are shared; each project has its own files and chats. */
export interface ProjectDef {
  id: string
  name: string
  /** Absolute, or relative to the app folder. */
  path: string
  /** Unset = mixed when the repo has its own agents, otherwise company. */
  team?: TeamMode
}

/** What the repo already brings: rules, its own agents, skills and commands. Read-only. */
export interface ProjectScan {
  claudeMd: boolean
  /** An AGENTS.md written by the owner (not generated by the app). */
  agentsMd: boolean
  settings: boolean
  mcp: boolean
  agents: { id: string; role: string; description: string; tools?: string[]; model?: string }[]
  skills: { name: string; description: string }[]
  commands: string[]
  /** A roadmap document the repo already keeps (e.g. docs/journey.md). */
  roadmap?: string
}

export interface ProjectRef extends ProjectDef {
  /** Resolved absolute folder. */
  dir: string
  exists: boolean
  scan?: ProjectScan
  /** Effective team mode. */
  mode: TeamMode
}

export type TaskStatus = 'todo' | 'doing' | 'review' | 'done' | 'blocked'

export interface PlanTask {
  id: string // "T1"
  title: string
  milestone?: string // "M1"
  assignee?: string
  status: TaskStatus
  note?: string
  updatedAt: number
}

/** The CEO's plan for one project. Progress = done tasks / all tasks. */
export interface Plan {
  projectId: string
  goal?: string
  milestones: { id: string; title: string }[]
  tasks: PlanTask[]
  updatedAt: number
}

export interface CompanyDef {
  name: L10n
  projects?: ProjectDef[]
  /** Where new tasks and chats go by default. */
  activeProject?: string
  /** Legacy single-folder setting; becomes the "Main" project. */
  workspace?: string
  /** What the business does. Empty until the CEO designs the company. */
  mission?: string
  rules?: string
}

export interface OrgDef {
  company: CompanyDef
  owner: OwnerDef
  divisions: DivisionDef[]
}

/** A role the CEO or HR wants to add. */
export interface HireSpec {
  id: string
  name: L10n
  role: L10n
  description: string
  prompt?: string
  tools?: string[]
  model?: string
  runtime?: Runtime
  sandbox?: Sandbox
  department: { id: string; name?: L10n }
}

export interface OrgDesign {
  company?: { name?: L10n; mission?: string; rules?: string }
  departments: { id: string; name: L10n; members: Omit<HireSpec, 'department'>[] }[]
}

export type ProposalKind = 'design' | 'hire' | 'dismiss'

export interface Proposal {
  id: string
  ts: number
  kind: ProposalKind
  from: string
  reason: string
  status: 'pending' | 'approved' | 'rejected'
  design?: OrgDesign
  hire?: HireSpec
  dismiss?: { id: string }
  /** Project of the run that proposed it, when there was one. */
  projectId?: string
}

export interface ChatMessage {
  id: string
  ts: number
  agentId: string
  role: 'owner' | 'agent' | 'note'
  text: string
  projectId?: string
  /** The agent asked the owner something (message_owner) and waits for an answer. */
  ask?: boolean
}

/** One project as seen from the portfolio. */
export interface ProjectSummary {
  id: string
  name: string
  dir: string
  exists: boolean
  mode: TeamMode
  running: boolean
  progress: { done: number; total: number; pct: number }
  counts: Record<TaskStatus, number>
  milestone?: string
  next?: { id: string; title: string; assignee?: string }
  working: { agentId: string; title: string }[]
  lastActivity?: number
  costUsd: number
  needs: { approvals: number; questions: number; blocked: number; manual: number }
}

export interface FileChange {
  path: string
  status: string // git porcelain code, e.g. "M", "A", "??"
  added?: number
  removed?: number
  /** Who touched it (from agent events), most recent first. */
  by: { agentId: string; taskId?: string; ts: number }[]
}

export interface ProjectChanges {
  git: boolean
  branch?: string
  files: FileChange[]
  commits: { hash: string; subject: string; author: string; when: string }[]
}

/** An agent flattened with its position in the org. */
export interface AgentRef extends AgentDef {
  divisionId: string
  departmentId: string | null
  runtime: Runtime
  isCeo: boolean
  manual: boolean
  managerId: string
  /** Defined in a repo's `.claude/agents` (read-only in the app), for this project. */
  external?: string
}

export type EventKind =
  | 'task' // owner → CEO
  | 'dispatch' // manager → member (or cross-division)
  | 'report' // member → manager
  | 'activity' // what an agent is doing right now
  | 'manual' // task queued for a manual (non-automated) agent
  | 'error'
  | 'chat' // a message in an owner ↔ agent chat
  | 'system'

export interface AgentEvent {
  id: string
  ts: number
  runId?: string
  projectId?: string
  kind: EventKind
  from?: string
  to?: string
  agent?: string
  text: string
  meta?: Record<string, unknown>
}

export interface RuntimeStatus {
  runtime: Runtime
  installed: boolean
  version?: string
  path?: string
  auth: 'ok' | 'missing' | 'unknown'
  mode: 'auto' | 'manual'
  note?: string
}

export interface CompiledFile {
  path: string // relative to workspace
  runtime: Runtime | 'shared'
  agentId?: string
  content: string
}

export interface ManualTask {
  id: string
  ts: number
  from: string
  to: string
  task: string
  prompt: string
  done: boolean
}
